<?php
/**
 * Builds admin/admin.css from admin/src/admin.full.css.
 *
 * The source is drawn at the size of the 1672 px reference image. On real screens that
 * looked too big, so computers and tablets (wider than 900 px) get everything at 70 %:
 * every px value and every breakpoint is multiplied by ADMIN_SCALE. Phones (900 px and
 * narrower) keep the full-size source, which is already sized for small screens.
 *
 * Run from the project folder:  php app/build-admin-css.php
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

const ADMIN_SCALE = 0.7;
const PHONE_MAX = 900;
const MIN_TEXT = 12.5; // no text smaller than this on computers, so small labels stay readable

$root = dirname(__DIR__);
$source = (string) file_get_contents($root . '/admin/src/admin.full.css');
$source = (string) preg_replace('#^/\*.*?\*/\s*#s', '', $source); // drop the source-file note

$px = static function (string $css): string {
    return (string) preg_replace_callback('/(?<![\w.#-])(\d*\.?\d+)px/', static function (array $m): string {
        $v = (float) $m[1];
        if ($v <= 2) {
            return $m[0]; // keep hairlines crisp
        }
        $s = round($v * ADMIN_SCALE * 2) / 2;
        return rtrim(rtrim(number_format($s, 1, '.', ''), '0'), '.') . 'px';
    }, $css);
};

// Every px value is scaled, including media-query widths (1500 -> 1050, 1180 -> 826 ...),
// so the layout switches at the same visual size as before.
$desktop = $px($source);
$desktop = (string) preg_replace_callback('/(font:\s*(?:italic\s+)?\d+\s+|font-size:\s*)([\d.]+)px/', static function (array $m): string {
    return $m[1] . max((float) $m[2], MIN_TEXT) . 'px';
}, $desktop);

$out = "/* GENERATED by app/build-admin-css.php from admin/src/admin.full.css — do not edit by hand. */\n"
    . "@media (min-width: " . (PHONE_MAX + 1) . "px) {\n" . $desktop . "\n}\n"
    . "@media (max-width: " . PHONE_MAX . "px) {\n" . $source . "\n}\n"
    // Edit forms are written at their final size already, so they are added as they are.
    . (string) file_get_contents($root . '/admin/src/forms.css');

file_put_contents($root . '/admin/admin.css', $out);
echo "admin/admin.css written (" . strlen($out) . " bytes)\n";
